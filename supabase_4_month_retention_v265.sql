-- AIS Tracker V265: automatic four-calendar-month history retention.
-- IMPORTANT: take a Supabase backup before installing. This migration schedules
-- daily deletion. Current master_catalog stock and active / partially shipped POs
-- are protected. Opening balances preserve cardboard and extrusion on-hand stock.
-- Run this file ONCE in Supabase SQL Editor as postgres.

create table if not exists public.cardboard_stock_opening_balances (
  cb_type text primary key,
  opening_boxes bigint not null default 0,
  as_of_date date not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.extrusion_stock_opening_balances (
  profile text not null,
  extrusion_length numeric(12,2) not null check (extrusion_length > 0),
  opening_qty bigint not null default 0,
  as_of_date date not null,
  updated_at timestamptz not null default now(),
  primary key (profile, extrusion_length)
);

create table if not exists public.ais_retention_runs (
  id bigint generated by default as identity primary key,
  run_at timestamptz not null default now(),
  cutoff_date date not null,
  deleted_rows jsonb not null default '{}'::jsonb,
  cardboard_balance_keys_snapshotted integer not null default 0,
  extrusion_balance_keys_snapshotted integer not null default 0,
  completed_pos_purged integer not null default 0
);

alter table public.cardboard_stock_opening_balances enable row level security;
alter table public.extrusion_stock_opening_balances enable row level security;
alter table public.ais_retention_runs enable row level security;

drop policy if exists "AIS cardboard opening balances read" on public.cardboard_stock_opening_balances;
create policy "AIS cardboard opening balances read" on public.cardboard_stock_opening_balances for select using (true);
drop policy if exists "AIS extrusion opening balances read" on public.extrusion_stock_opening_balances;
create policy "AIS extrusion opening balances read" on public.extrusion_stock_opening_balances for select using (true);
drop policy if exists "AIS retention runs admin read" on public.ais_retention_runs;
create policy "AIS retention runs admin read" on public.ais_retention_runs for select using (auth.role() = 'service_role');

grant select on public.cardboard_stock_opening_balances to anon, authenticated;
grant select on public.extrusion_stock_opening_balances to anon, authenticated;
revoke all on public.ais_retention_runs from anon, authenticated;

create or replace function public.run_ais_4_month_retention()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_cutoff date := (current_date - interval '4 months')::date;
  v_deleted jsonb := '{}'::jsonb;
  v_count bigint := 0;
  v_card_keys integer := 0;
  v_ex_keys integer := 0;
  v_completed_pos integer := 0;
  v_job_id bigint;
begin
  -- Determine fully shipped POs first. A PO is completed only when every
  -- PO/profile/length line is fully covered by shipment quantities.
  create temporary table ais_retention_completed_po (
    po_number text primary key,
    completed_at date not null
  ) on commit drop;

  if to_regclass('public.production_orders') is not null and to_regclass('public.shipments') is not null then
    insert into pg_temp.ais_retention_completed_po(po_number,completed_at)
    with po_lines as (
      select btrim(po_number) po_number, profile,
             round(nullif(regexp_replace(length::text,'[^0-9.]','','g'),'')::numeric,3) line_length,
             sum(order_qty)::numeric required_qty
        from public.production_orders
       where nullif(btrim(po_number),'') is not null
       group by btrim(po_number), profile,
                round(nullif(regexp_replace(length::text,'[^0-9.]','','g'),'')::numeric,3)
    ), shipped_lines as (
      select btrim(po_number) po_number, profile,
             round(nullif(regexp_replace(length::text,'[^0-9.]','','g'),'')::numeric,3) line_length,
             sum(shipped_qty)::numeric shipped_qty, max(shipment_date)::date last_shipment
        from public.shipments
       where nullif(btrim(po_number),'') is not null
       group by btrim(po_number), profile,
                round(nullif(regexp_replace(length::text,'[^0-9.]','','g'),'')::numeric,3)
    ), status as (
      select p.po_number,
             bool_and(coalesce(s.shipped_qty,0) >= p.required_qty) as fully_shipped,
             max(s.last_shipment) as completed_at
        from po_lines p
        left join shipped_lines s
          on s.po_number=p.po_number and s.profile=p.profile and s.line_length=p.line_length
       group by p.po_number
    )
    select po_number, completed_at from status
     where fully_shipped is true and completed_at < v_cutoff;

    select count(*) into v_completed_pos from pg_temp.ais_retention_completed_po;
  end if;

  -- Snapshot the NET historical cardboard contribution before deleting old transactions.
  if to_regclass('public.cardboard_stock') is not null then
    insert into public.cardboard_stock_opening_balances(cb_type, opening_boxes, as_of_date, updated_at)
    select cb_type, coalesce(sum(coalesce(incoming,0) - coalesce(used,0)),0)::bigint, v_cutoff, now()
      from public.cardboard_stock
     where cb_date < v_cutoff and nullif(btrim(cb_type),'') is not null
     group by cb_type
    on conflict (cb_type) do update
      set opening_boxes = public.cardboard_stock_opening_balances.opening_boxes + excluded.opening_boxes,
          as_of_date = excluded.as_of_date,
          updated_at = now();
    get diagnostics v_card_keys = row_count;
    delete from public.cardboard_stock where cb_date < v_cutoff;
    get diagnostics v_count = row_count;
    v_deleted := jsonb_set(v_deleted,'{cardboard_stock}',to_jsonb(v_count),true);
  end if;

  -- Snapshot old extrusion IN + movement net - actual saved Cut deductions.
  -- Old receipt rows tied to an ACTIVE PO are deliberately retained so the
  -- PO-specific receipt allocation does not get lost. The old receipt history
  -- for unlinked / purged POs is carried into the physical opening balance.
  if to_regclass('public.extrusion_receipts') is not null
     and to_regclass('public.extrusion_stock_movements') is not null
     and to_regclass('public.extrusion_cut_usage') is not null
     and to_regclass('public.production_orders') is not null then
    insert into public.extrusion_stock_opening_balances(profile, extrusion_length, opening_qty, as_of_date, updated_at)
    with old_receipts as (
      select r.profile, r.extrusion_length, sum(r.in_qty)::bigint qty
        from public.extrusion_receipts r
       where r.receipt_date < v_cutoff
         and (nullif(btrim(r.po_number),'') is null
              or r.po_number in (select po_number from pg_temp.ais_retention_completed_po)
              or not exists (select 1 from public.production_orders p where p.po_number=r.po_number))
       group by r.profile, r.extrusion_length
    ), keys as (
      select profile, extrusion_length from old_receipts
      union
      select profile, extrusion_length from public.extrusion_stock_movements where movement_date < v_cutoff
      union
      select profile, extrusion_length from public.extrusion_cut_usage where movement_date < v_cutoff
    ), old_moves as (
      select profile, extrusion_length, sum(qty_change)::bigint qty from public.extrusion_stock_movements
       where movement_date < v_cutoff group by profile, extrusion_length
    ), old_cuts as (
      select profile, extrusion_length, sum(deducted_extrusions)::bigint qty from public.extrusion_cut_usage
       where movement_date < v_cutoff group by profile, extrusion_length
    )
    select k.profile, k.extrusion_length,
           coalesce(r.qty,0) + coalesce(m.qty,0) - coalesce(c.qty,0), v_cutoff, now()
      from keys k
      left join old_receipts r using(profile,extrusion_length)
      left join old_moves m using(profile,extrusion_length)
      left join old_cuts c using(profile,extrusion_length)
    on conflict (profile,extrusion_length) do update
      set opening_qty = public.extrusion_stock_opening_balances.opening_qty + excluded.opening_qty,
          as_of_date = excluded.as_of_date,
          updated_at = now();
    get diagnostics v_ex_keys = row_count;

    delete from public.extrusion_cut_usage where movement_date < v_cutoff;
    get diagnostics v_count = row_count;
    v_deleted := jsonb_set(v_deleted,'{extrusion_cut_usage}',to_jsonb(v_count),true);
    delete from public.extrusion_stock_movements where movement_date < v_cutoff;
    get diagnostics v_count = row_count;
    v_deleted := jsonb_set(v_deleted,'{extrusion_stock_movements}',to_jsonb(v_count),true);
    delete from public.extrusion_receipts r
     where r.receipt_date < v_cutoff
       and (nullif(btrim(r.po_number),'') is null
            or r.po_number in (select po_number from pg_temp.ais_retention_completed_po)
            or not exists (select 1 from public.production_orders p where p.po_number=r.po_number));
    get diagnostics v_count = row_count;
    v_deleted := jsonb_set(v_deleted,'{extrusion_receipts}',to_jsonb(v_count),true);
  end if;

  -- Delete PL, shipment and PO rows only for POs fully shipped more than four months ago.
  if to_regclass('public.production_orders') is not null and to_regclass('public.shipments') is not null then
    if to_regclass('public.packing_list') is not null then
      delete from public.packing_list pl
       where pl.packing_date < v_cutoff
         and pl.po_number in (select po_number from pg_temp.ais_retention_completed_po);
      get diagnostics v_count = row_count;
      v_deleted := jsonb_set(v_deleted,'{packing_list}',to_jsonb(v_count),true);
    end if;

    delete from public.shipments s
     where s.po_number in (select po_number from pg_temp.ais_retention_completed_po);
    get diagnostics v_count = row_count;
    v_deleted := jsonb_set(v_deleted,'{shipments}',to_jsonb(v_count),true);

    delete from public.production_orders p
     where p.po_number in (select po_number from pg_temp.ais_retention_completed_po);
    get diagnostics v_count = row_count;
    v_deleted := jsonb_set(v_deleted,'{production_orders}',to_jsonb(v_count),true);
  end if;

  -- Ordinary dated history tables. Master Catalog and its live stage stock fields are untouched.
  if to_regclass('public.history_logs') is not null then
    delete from public.history_logs where log_date < v_cutoff;
    get diagnostics v_count = row_count; v_deleted:=jsonb_set(v_deleted,'{history_logs}',to_jsonb(v_count),true);
  end if;
  if to_regclass('public.reject_logs') is not null then
    delete from public.reject_logs where reject_date < v_cutoff;
    get diagnostics v_count = row_count; v_deleted:=jsonb_set(v_deleted,'{reject_logs}',to_jsonb(v_count),true);
  end if;
  if to_regclass('public.recover_logs') is not null then
    delete from public.recover_logs where recover_date < v_cutoff;
    get diagnostics v_count = row_count; v_deleted:=jsonb_set(v_deleted,'{recover_logs}',to_jsonb(v_count),true);
  end if;
  if to_regclass('public.recovery_cut_logs') is not null then
    delete from public.recovery_cut_logs where cut_date < v_cutoff;
    get diagnostics v_count = row_count; v_deleted:=jsonb_set(v_deleted,'{recovery_cut_logs}',to_jsonb(v_count),true);
  end if;
  if to_regclass('public.recovery_wrap_logs') is not null then
    delete from public.recovery_wrap_logs where wrap_date < v_cutoff;
    get diagnostics v_count = row_count; v_deleted:=jsonb_set(v_deleted,'{recovery_wrap_logs}',to_jsonb(v_count),true);
  end if;
  if to_regclass('public.daily_team_plans') is not null then
    delete from public.daily_team_plans where plan_date < v_cutoff;
    get diagnostics v_count = row_count; v_deleted:=jsonb_set(v_deleted,'{daily_team_plans}',to_jsonb(v_count),true);
  end if;
  if to_regclass('public.stock_shift_snapshots') is not null then
    delete from public.stock_shift_snapshots where snapshot_date < v_cutoff;
    get diagnostics v_count = row_count; v_deleted:=jsonb_set(v_deleted,'{stock_shift_snapshots}',to_jsonb(v_count),true);
  end if;
  if to_regclass('public.daily_instructions') is not null then
    delete from public.daily_instructions
     where target_date < v_cutoff
       and left(coalesce(target_user,''),4) <> 'SYS_';
    get diagnostics v_count = row_count; v_deleted:=jsonb_set(v_deleted,'{daily_instructions}',to_jsonb(v_count),true);
  end if;

  insert into public.ais_retention_runs(cutoff_date,deleted_rows,cardboard_balance_keys_snapshotted,extrusion_balance_keys_snapshotted,completed_pos_purged)
  values(v_cutoff,v_deleted,v_card_keys,v_ex_keys,v_completed_pos);

  return jsonb_build_object('success',true,'cutoff_date',v_cutoff,'deleted_rows',v_deleted,
    'cardboard_balance_keys_snapshotted',v_card_keys,'extrusion_balance_keys_snapshotted',v_ex_keys,
    'completed_pos_purged',v_completed_pos);
end;
$$;

revoke all on function public.run_ais_4_month_retention() from public, anon, authenticated;
grant execute on function public.run_ais_4_month_retention() to service_role;

-- Enable pg_cron in Supabase Dashboard first if your project has not enabled it.
create extension if not exists pg_cron with schema pg_catalog;
select cron.unschedule(jobid) from cron.job where jobname = 'ais-tracker-4-month-retention';
select cron.schedule('ais-tracker-4-month-retention','15 2 * * *','select public.run_ais_4_month_retention();');

