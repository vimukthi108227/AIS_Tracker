-- AIS Tracker Extrusion module (additive migration only)
-- Run once in Supabase SQL Editor. Does not alter or delete existing tables/data.
create table if not exists public.extrusion_receipts (
  id bigint generated by default as identity primary key,
  receipt_date date not null,
  profile text not null,
  extrusion_length numeric(12,2) not null check (extrusion_length > 0),
  trolley_no text not null,
  in_qty integer not null check (in_qty > 0),
  note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists extrusion_receipts_profile_length_idx on public.extrusion_receipts(profile, extrusion_length);
create index if not exists extrusion_receipts_date_idx on public.extrusion_receipts(receipt_date desc);
-- Add PO linkage without deleting or rewriting existing receipt records.
alter table public.extrusion_receipts add column if not exists po_number text;
create index if not exists extrusion_receipts_po_profile_length_idx on public.extrusion_receipts(po_number, profile, extrusion_length);

alter table public.extrusion_receipts enable row level security;
