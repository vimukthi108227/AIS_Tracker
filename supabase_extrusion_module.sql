-- AIS Tracker Extrusion module (additive migration only)
-- Run once in Supabase SQL Editor. Does not alter or delete existing tables/data.
create table if not exists public.extrusion_receipts (
  id bigint generated by default as identity primary key,
  receipt_date date not null,
  profile text not null,
  extrusion_length numeric(12,2) not null check (extrusion_length > 0),
  trolley_no text not null,
  in_qty integer not null check (in_qty > 0),
  note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists extrusion_receipts_profile_length_idx on public.extrusion_receipts(profile, extrusion_length);
create index if not exists extrusion_receipts_date_idx on public.extrusion_receipts(receipt_date desc);
-- Add PO linkage without deleting or rewriting existing receipt records.
alter table public.extrusion_receipts add column if not exists po_number text;
create index if not exists extrusion_receipts_po_profile_length_idx on public.extrusion_receipts(po_number, profile, extrusion_length);

alter table public.extrusion_receipts enable row level security;
-- Policies use the same publishable-key access pattern as this existing app.
-- Review and tighten these policies to match your production security model before deployment.
drop policy if exists "AIS extrusion receipts read" on public.extrusion_receipts;
create policy "AIS extrusion receipts read" on public.extrusion_receipts for select using (true);
drop policy if exists "AIS extrusion receipts insert" on public.extrusion_receipts;
create policy "AIS extrusion receipts insert" on public.extrusion_receipts for insert with check (true);
drop policy if exists "AIS extrusion receipts update" on public.extrusion_receipts;
create policy "AIS extrusion receipts update" on public.extrusion_receipts for update using (true) with check (true);
drop policy if exists "AIS extrusion receipts delete" on public.extrusion_receipts;
create policy "AIS extrusion receipts delete" on public.extrusion_receipts for delete using (true);


-- V256 stock movement ledger (additive; preserves all existing receipts)
-- AIS Tracker Extrusion Stock Ledger V256 (additive migration)
-- Safe to run more than once. Existing extrusion_receipts and all PO data remain unchanged.
create table if not exists public.extrusion_stock_movements (
  id bigint generated by default as identity primary key,
  movement_date date not null default current_date,
  profile text not null,
  extrusion_length numeric(12,2) not null check (extrusion_length > 0),
  movement_type text not null check (movement_type in ('IN','OUT','SET')),
  qty_change integer not null check (qty_change <> 0),
  note text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists extrusion_stock_movements_profile_length_idx
  on public.extrusion_stock_movements(profile, extrusion_length);
create index if not exists extrusion_stock_movements_date_idx
  on public.extrusion_stock_movements(movement_date desc);
alter table public.extrusion_stock_movements enable row level security;
drop policy if exists "AIS extrusion stock movements read" on public.extrusion_stock_movements;
create policy "AIS extrusion stock movements read" on public.extrusion_stock_movements for select using (true);
drop policy if exists "AIS extrusion stock movements insert" on public.extrusion_stock_movements;
create policy "AIS extrusion stock movements insert" on public.extrusion_stock_movements for insert with check (true);

-- REST permissions for the additive extrusion stock ledger.
grant select, insert on public.extrusion_stock_movements to anon, authenticated;
grant usage, select on sequence public.extrusion_stock_movements_id_seq to anon, authenticated;
