-- AIS Tracker V261: additive Daily Production Cut -> Extrusion Stock usage ledger.
-- Safe to run repeatedly. Existing production history, Master Catalog, extrusion
-- receipts, stock movements, Packing Lists and PO records are NOT rewritten.
-- Run once in Supabase SQL Editor before deploying the V261 frontend.

create table if not exists public.extrusion_cut_usage (
  id bigint generated by default as identity primary key,
  source_history_id bigint not null,
  movement_date date not null,
  shift text not null default '',
  team text not null default '',
  profile text not null,
  item_code text not null default '',
  cut_length numeric(12,3) not null check (cut_length > 0),
  extrusion_length numeric(12,2) not null check (extrusion_length > 0),
  cut_pcs integer not null check (cut_pcs > 0),
  pcs_per_extrusion integer not null check (pcs_per_extrusion > 0),
  required_extrusions integer not null check (required_extrusions > 0),
  deducted_extrusions integer not null default 0 check (deducted_extrusions >= 0),
  short_extrusions integer not null default 0 check (short_extrusions >= 0),
  note text not null default '',
  created_at timestamptz not null default now(),
  constraint extrusion_cut_usage_history_once unique (source_history_id),
  constraint extrusion_cut_usage_reconcile check (deducted_extrusions + short_extrusions = required_extrusions)
);

create index if not exists extrusion_cut_usage_date_idx
  on public.extrusion_cut_usage(movement_date desc, id desc);
create index if not exists extrusion_cut_usage_profile_length_idx
  on public.extrusion_cut_usage(profile, extrusion_length);

alter table public.extrusion_cut_usage enable row level security;

drop policy if exists "AIS extrusion cut usage read" on public.extrusion_cut_usage;
create policy "AIS extrusion cut usage read"
  on public.extrusion_cut_usage for select using (true);

drop policy if exists "AIS extrusion cut usage insert" on public.extrusion_cut_usage;
create policy "AIS extrusion cut usage insert"
  on public.extrusion_cut_usage for insert with check (true);

drop policy if exists "AIS extrusion cut usage delete" on public.extrusion_cut_usage;
create policy "AIS extrusion cut usage delete"
  on public.extrusion_cut_usage for delete using (true);

grant select, insert, delete on public.extrusion_cut_usage to anon, authenticated;
grant usage, select on sequence public.extrusion_cut_usage_id_seq to anon, authenticated;

comment on table public.extrusion_cut_usage is
  'Append-only audit ledger for automatic extrusion consumption from saved Daily Production Cut entries. One row per history_logs ID.';

-- Atomic, idempotent stock deduction for simultaneous production entries.
-- The advisory lock serializes consumption for each Profile + Extrusion Length.
do $$
begin
  if to_regclass('public.extrusion_receipts') is null
     or to_regclass('public.extrusion_stock_movements') is null then
    raise exception 'Run supabase_extrusion_module.sql and supabase_extrusion_stock_ledger_v256.sql before this V261 migration.';
  end if;
end $$;

create or replace function public.record_extrusion_cut_usage(
  p_source_history_id bigint,
  p_movement_date date,
  p_shift text,
  p_team text,
  p_profile text,
  p_item_code text,
  p_cut_length numeric,
  p_extrusion_length numeric,
  p_cut_pcs integer,
  p_pcs_per_extrusion integer,
  p_required_extrusions integer,
  p_note text default ''
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_existing public.extrusion_cut_usage%rowtype;
  v_receipts bigint := 0;
  v_movements bigint := 0;
  v_used bigint := 0;
  v_available bigint := 0;
  v_deducted integer := 0;
  v_short integer := 0;
  v_saved public.extrusion_cut_usage%rowtype;
  v_lock_key text;
begin
  if p_source_history_id is null or p_cut_pcs is null or p_cut_pcs <= 0
     or p_pcs_per_extrusion is null or p_pcs_per_extrusion <= 0
     or p_required_extrusions is null or p_required_extrusions <= 0
     or p_profile is null or btrim(p_profile) = ''
     or p_extrusion_length is null or p_extrusion_length <= 0 then
    raise exception 'Invalid production Cut extrusion usage values.';
  end if;

  -- A retry for an already saved history row returns its original movement.
  select * into v_existing
    from public.extrusion_cut_usage
   where source_history_id = p_source_history_id;
  if found then
    return to_jsonb(v_existing);
  end if;

  v_lock_key := lower(btrim(p_profile)) || '|' || round(p_extrusion_length, 2)::text;
  perform pg_advisory_xact_lock(hashtextextended(v_lock_key, 0));

  -- Re-check after acquiring the lock in case another request inserted it.
  select * into v_existing
    from public.extrusion_cut_usage
   where source_history_id = p_source_history_id;
  if found then
    return to_jsonb(v_existing);
  end if;

  select coalesce(sum(in_qty), 0) into v_receipts
    from public.extrusion_receipts
   where lower(btrim(profile)) = lower(btrim(p_profile))
     and round(extrusion_length, 2) = round(p_extrusion_length, 2);

  select coalesce(sum(qty_change), 0) into v_movements
    from public.extrusion_stock_movements
   where lower(btrim(profile)) = lower(btrim(p_profile))
     and round(extrusion_length, 2) = round(p_extrusion_length, 2);

  select coalesce(sum(deducted_extrusions), 0) into v_used
    from public.extrusion_cut_usage
   where lower(btrim(profile)) = lower(btrim(p_profile))
     and round(extrusion_length, 2) = round(p_extrusion_length, 2);

  v_available := greatest(0, v_receipts + v_movements - v_used);
  v_deducted := least(v_available, p_required_extrusions)::integer;
  v_short := p_required_extrusions - v_deducted;

  insert into public.extrusion_cut_usage(
    source_history_id, movement_date, shift, team, profile, item_code,
    cut_length, extrusion_length, cut_pcs, pcs_per_extrusion,
    required_extrusions, deducted_extrusions, short_extrusions, note
  ) values (
    p_source_history_id, p_movement_date, coalesce(p_shift, ''), coalesce(p_team, ''),
    btrim(p_profile), coalesce(p_item_code, ''), p_cut_length, p_extrusion_length,
    p_cut_pcs, p_pcs_per_extrusion, p_required_extrusions,
    v_deducted, v_short, coalesce(p_note, '')
  )
  on conflict (source_history_id) do nothing
  returning * into v_saved;

  if not found then
    select * into v_saved from public.extrusion_cut_usage
     where source_history_id = p_source_history_id;
  end if;

  return to_jsonb(v_saved);
end;
$$;

grant execute on function public.record_extrusion_cut_usage(
  bigint, date, text, text, text, text, numeric, numeric, integer, integer, integer, text
) to anon, authenticated;
