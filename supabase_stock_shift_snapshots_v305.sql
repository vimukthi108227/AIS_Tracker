-- AIS Tracker V305: additive shift-closing stock snapshots.
-- This table is separate from master_catalog and does not update/delete any existing stock records.
-- Run once in Supabase SQL Editor before deploying the V305 frontend.

create table if not exists public.stock_shift_snapshots (
  id bigint generated by default as identity primary key,
  snapshot_date date not null,
  shift text not null check (shift in ('Day', 'Night')),
  stock_data jsonb not null default '[]'::jsonb,
  captured_at timestamptz not null default now(),
  captured_by uuid null,
  constraint stock_shift_snapshots_date_shift_key unique (snapshot_date, shift)
);

create index if not exists stock_shift_snapshots_date_idx
  on public.stock_shift_snapshots(snapshot_date desc);

alter table public.stock_shift_snapshots enable row level security;

drop policy if exists "AIS stock shift snapshots read" on public.stock_shift_snapshots;
create policy "AIS stock shift snapshots read"
  on public.stock_shift_snapshots for select using (true);

drop policy if exists "AIS stock shift snapshots insert" on public.stock_shift_snapshots;
create policy "AIS stock shift snapshots insert"
  on public.stock_shift_snapshots for insert with check (true);

drop policy if exists "AIS stock shift snapshots update" on public.stock_shift_snapshots;
create policy "AIS stock shift snapshots update"
  on public.stock_shift_snapshots for update using (true) with check (true);

grant select, insert, update on public.stock_shift_snapshots to anon, authenticated;
grant usage, select on sequence public.stock_shift_snapshots_id_seq to anon, authenticated;

-- No historical snapshots are fabricated by this migration.
-- Each snapshot is saved only when an Admin presses "Save Shift Closing Stock".
